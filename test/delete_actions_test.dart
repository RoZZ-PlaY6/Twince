import 'package:flutter/material.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:twince/models/task.dart';
import 'package:twince/screens/home_screen.dart';
import 'package:twince/screens/plan_screen.dart';
import 'package:twince/widgets/task_card.dart';

void main() {
  testWidgets(
      'deleting one occurrence stays immediate and has no series dialog',
      (tester) async {
    var deleted = false;
    final day = DateTime(2026, 10, 20);
    await tester.pumpWidget(MaterialApp(
      home: Scaffold(
        body: TaskCard(
          task: Task(
            title: 'One off',
            targetDate: day,
            startTime: DateTime(2026, 10, 20, 22),
            endTime: DateTime(2026, 10, 20, 22, 30),
          ),
          onToggle: () {},
          onDelete: () => deleted = true,
          onEdit: () {},
          onExpire: () async {},
        ),
      ),
    ));

    expect(find.text('Delete all'), findsNothing);
    await tester.tap(find.byTooltip('Delete task'));
    await tester.pump();

    expect(deleted, isTrue);
    expect(find.text('Delete recurring task?'), findsNothing);
  });

  testWidgets('delete all explains that every occurrence will be removed',
      (tester) async {
    bool? confirmed;
    await tester.pumpWidget(MaterialApp(
      home: Scaffold(
        body: Builder(
          builder: (context) => TextButton(
            onPressed: () async =>
                confirmed = await confirmDeleteAllOccurrences(context),
            child: const Text('Open delete all'),
          ),
        ),
      ),
    ));

    await tester.tap(find.text('Open delete all'));
    await tester.pumpAndSettle();
    expect(
      find.text(
          'All occurrences of this recurring task, including completed and failed ones, will be deleted.'),
      findsOneWidget,
    );
    await tester.tap(find.text('Cancel'));
    await tester.pumpAndSettle();
    expect(confirmed, isFalse);

    await tester.tap(find.text('Open delete all'));
    await tester.pumpAndSettle();
    await tester.tap(find.widgetWithText(FilledButton, 'Delete all'));
    await tester.pumpAndSettle();
    expect(confirmed, isTrue);
  });

  testWidgets('deleting a plan requires confirmation', (tester) async {
    bool? confirmed;
    await tester.pumpWidget(MaterialApp(
      home: Scaffold(
        body: Builder(
          builder: (context) => TextButton(
            onPressed: () async =>
                confirmed = await confirmDeletePlan(context, 'Semester'),
            child: const Text('Open delete plan'),
          ),
        ),
      ),
    ));

    await tester.tap(find.text('Open delete plan'));
    await tester.pumpAndSettle();
    expect(find.text('Delete plan?'), findsOneWidget);
    expect(find.textContaining('Semester'), findsOneWidget);
    expect(find.textContaining('all tasks generated by this plan'),
        findsOneWidget);
    await tester.tap(find.text('Delete plan'));
    await tester.pumpAndSettle();
    expect(confirmed, isTrue);
  });
}
